#!/usr/bin/env bash
# Self-test of the c_perf rule and the perf harness (T076).
# Builds fixtures in a scratch package, twice (two copies that differ in a comment, so both are cold
# builds with their own keys), and asserts the cost counts: ratios per fixture, identical counts across
# the two copies, and the failure statuses. Needs bash, python3 (stdlib) and tools/buck2.
set -uo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$root"
B=(tools/buck2)
PLAT=toolchains//:linux_release
scratch="selftest/scratch_perf"
out="$(mktemp -d)"
trap 'rm -rf "$scratch" "$out"' EXIT
nonce="$$-$(date +%s%N)"

fail() { echo "FAIL: $1" >&2; [ -n "${2:-}" ] && { echo "---- output ----" >&2; tail -n 40 "$2" >&2; }; exit 1; }

# ---- fixtures ---------------------------------------------------------------------------------
# name:sizes. Each module is one function over the generated bytes.
fixtures="lin:20000,80000 quad:3000,12000 mmove:10000,40000 ovf:100,400 rerr:100,400 segv:100,400"

mkdir -p "$scratch/@"
cat > "$scratch/@/gen.inc" <<'C'
static size_t fill(uint64_t seed, size_t n, char *out, size_t cap) {
    uint64_t x = seed * 6364136223846793005ULL + 1442695040888963407ULL;
    size_t i;
    if (n > cap) { return 0; }
    for (i = 0; i < n; i++) {
        x = x * 6364136223846793005ULL + 1442695040888963407ULL;
        out[i] = (char)('a' + (x >> 60) % 7);
    }
    return n;
}
C
for f in $fixtures; do
  n="${f%%:*}"
  printf '#include <stddef.h>\n#include <stdint.h>\nuint64_t %s_work(const char *in, size_t len);\n' "$n" > "$scratch/@/$n.h"
done
cat > "$scratch/@/lin.c" <<'C'
#include <stddef.h>
#include <stdint.h>
uint64_t lin_work(const char *in, size_t len) {
    uint64_t h = 0;
    for (size_t i = 0; i < len; i++) { h = h * 31u + (unsigned char)in[i]; }
    return h;
}
C
cat > "$scratch/@/quad.c" <<'C'
#include <stddef.h>
#include <stdint.h>
uint64_t quad_work(const char *in, size_t len) {
    uint64_t c = 0;
    for (size_t i = 0; i < len; i++) {
        for (size_t j = 0; j < i; j++) { c += (uint64_t)(in[i] == in[j]); }
    }
    return c;
}
C
# Quadratic bytes in libc, few instructions: delete the first byte repeatedly.
cat > "$scratch/@/mmove.c" <<'C'
#include <stddef.h>
#include <stdint.h>
#include <string.h>
static char g_buf[1 << 20];
uint64_t mmove_work(const char *in, size_t len) {
    size_t n = len;
    memcpy(g_buf, in, len);
    while (n > 1) { memmove(g_buf, g_buf + 1, n - 1); n--; }
    return (uint64_t)(unsigned char)g_buf[0];
}
C
printf '#include <stddef.h>\n#include <stdint.h>\nuint64_t ovf_work(const char *in, size_t len) { return (uint64_t)(unsigned char)in[0] + len; }\n' > "$scratch/@/ovf.c"
printf '#include <stddef.h>\n#include <stdint.h>\nuint64_t rerr_work(const char *in, size_t len) { (void)in; return len > 0 ? UINT64_MAX : 0; }\n' > "$scratch/@/rerr.c"
printf '#include <stddef.h>\n#include <stdint.h>\nstatic int *volatile g_null;\nuint64_t segv_work(const char *in, size_t len) { (void)in; *g_null = 1; return len; }\n' > "$scratch/@/segv.c"

for f in $fixtures; do
  n="${f%%:*}"
  extra=""
  # ovf: the generator ignores cap and writes past it.
  if [ "$n" = ovf ]; then
    cat > "$scratch/@/${n}_drv.c" <<C
#include <string.h>
#include "ctest/perf.h"
#include "selftest/scratch_perf/@/$n.h"
size_t perf_gen(uint64_t seed, size_t n, char *out, size_t cap) { (void)seed; (void)n; memset(out, 'x', cap + 8); return cap + 8; }
uint64_t perf_run(const char *in, size_t len) { return ${n}_work(in, len); }
C
  else
    cat > "$scratch/@/${n}_drv.c" <<C
#include "ctest/perf.h"
#include "selftest/scratch_perf/@/$n.h"
@GEN@
size_t perf_gen(uint64_t seed, size_t n, char *out, size_t cap) { return fill(seed, n, out, cap); }
uint64_t perf_run(const char *in, size_t len) { return ${n}_work(in, len); }
C
  fi
done
for d in "$scratch"/@/*_drv.c; do
  if grep -q "^@GEN@" "$d"; then
    { sed -n "1,/^@GEN@/p" "$d" | sed "\$d"; cat "$scratch/@/gen.inc"; sed -n "/^@GEN@/,\$p" "$d" | sed 1d; } > "$d.new" && mv "$d.new" "$d"
  fi
done
rm -f "$scratch/@/gen.inc"

{
  echo 'load("@gate//rules:c.bzl", "c_library", "c_perf")'
  for f in $fixtures; do
    n="${f%%:*}"; sz="${f##*:}"
    echo "c_library(name = \"$n\", srcs = [\"$n.c\"], headers = [\"$n.h\"])"
    echo "c_perf(name = \"${n}_p\", module = \":$n\", srcs = [\"${n}_drv.c\"], sizes = [${sz}], seed = 7)"
  done
} > "$scratch/@/BUCK"

# Two copies. The copies differ in a nonce (a comment in BUCK and headers, a string constant in the .c files, which changes
# the object and so the binary), so both are cold: compile, link and the perf run itself re-execute on whichever worker is free.
for c in a b; do
  mkdir -p "$scratch/$c"
  for file in "$scratch"/@/*; do
    dst="$scratch/$c/$(basename "$file")"
    sed "s|/@/|/$c/|g" "$file" > "$dst"
    case "$dst" in */BUCK) echo "# nonce $nonce $c" >> "$dst" ;; *.c) echo "__attribute__((used)) static const char perf_nonce[] = \"$nonce $c\";" >> "$dst" ;; *) echo "/* nonce $nonce $c */" >> "$dst" ;; esac
  done
done
rm -rf "$scratch/@"

targets=()
for c in a b; do
  for f in $fixtures; do targets+=("//selftest/scratch_perf/$c:${f%%:*}_p_perf"); done
done
log="$out/build.log"
"${B[@]}" build --target-platforms "$PLAT" "${targets[@]}" --show-output 2>&1 | sed 's/\x1b\[[0-9;]*m//g' > "$log"
[ "${PIPESTATUS[0]}" -eq 0 ] || fail "build failed" "$log"
for c in a b; do
  for f in $fixtures; do
    n="${f%%:*}"
    p="$(awk -v t="scratch_perf/$c:${n}_p_perf" 'index($1, t) && /buck-out/ {print $2}' "$log" | tail -1)"
    [ -f "$p" ] || fail "no perf.jsonl for $c/$n: '$p'" "$log"
    cp "$p" "$out/$c.$n.jsonl"
  done
done

python3 - "$out" $fixtures <<'PY' || exit 1
import json, sys
out = sys.argv[1]
fixtures = [f.split(":")[0] for f in sys.argv[2:]]
sys.path.insert(0, "gate")
from rigor_lib import perf_judge
# Exact between two cold runs. `instructions` agrees within perf_judge.count_bound (docs/perf.md "Determinism").
DET = ("name", "seed", "n", "status", "counter", "errno", "input_len", "libc_bytes", "result")

def load(c, n):
    with open("%s/%s.%s.jsonl" % (out, c, n)) as fh:
        return [json.loads(line) for line in fh]

bad = []
def check(cond, msg):
    if not cond:
        bad.append(msg)

recs = {}
for n in fixtures:
    a, b = load("a", n), load("b", n)
    recs[n] = a
    check(len(a) == 2 and len(b) == 2, "%s: expected 2 records" % n)
    for ra, rb in zip(a, b):
        da = {k: ra.get(k) for k in DET}
        db = {k: rb.get(k) for k in DET}
        check(da == db, "%s: counts differ between cold runs: %s vs %s" % (n, da, db))
        ia, ib = ra.get("instructions"), rb.get("instructions")
        check((ia is None) == (ib is None) and (ia is None or perf_judge.counts_agree(ia, ib)),
              "%s: instructions differ beyond the bound between cold runs: %s vs %s" % (n, ia, ib))
        check("wall_ns_median" in ra or ra["status"] != "ok", "%s: no wall field" % n)

# The agreement rule itself, on synthetic records: one instruction apart agrees, far apart differs.
syn = lambda v: {"instructions": v}
check(perf_judge.counts_agree(syn(342312029)["instructions"], syn(342312028)["instructions"]), "synthetic: one apart must agree")
check(not perf_judge.counts_agree(342312029, 342312029 * 2), "synthetic: far apart must differ")
check(not perf_judge.counts_agree(115051, 115051 + perf_judge.count_bound(115051, 115051) + 1), "synthetic: just past the bound must differ")

def ratio(n, field):
    lo, hi = recs[n]
    return hi[field] / lo[field]

unavailable = any(r.get("counter") == "unavailable" for n in ("lin", "quad", "mmove") for r in recs[n])
for n in ("lin", "quad", "mmove"):
    check(all(r["status"] == "ok" for r in recs[n]), "%s: status %s" % (n, [r["status"] for r in recs[n]]))
if unavailable:
    print("perf: counter unavailable here (recorded, not a failure of the rule)")
    check(all(r["counter"] == "unavailable" and (r["errno"] != 0 or r.get("why")) and r["instructions"] is None for r in recs["lin"]), "lin: unavailable without errno")
else:
    rl, rq, rm = ratio("lin", "instructions"), ratio("quad", "instructions"), ratio("mmove", "instructions")
    bm = ratio("mmove", "libc_bytes")
    print("ratios: lin instr %.3f; quad instr %.3f; mmove bytes %.3f, instr %.3f" % (rl, rq, bm, rm))
    check(3.5 <= rl <= 5, "lin instruction ratio %.3f not in [3.5, 5]" % rl)
    check(rq >= 12, "quad instruction ratio %.3f < 12" % rq)
    check(bm >= 12, "mmove byte ratio %.3f < 12" % bm)
    check(rm < 6, "mmove instruction ratio %.3f is not low" % rm)
    check(all(r["libc_bytes"] == 0 for r in recs["quad"]), "quad: libc bytes should be 0")

st = lambda n: [r["status"] for r in recs[n]]
check(st("ovf") == ["gen-overflow"] * 2, "ovf: %s" % st("ovf"))
check(st("rerr") == ["run-error"] * 2, "rerr: %s" % st("rerr"))
check(st("segv") == ["crash"] * 2 and all(r.get("signal") == 11 for r in recs["segv"]), "segv: %s" % recs["segv"])
for n in ("ovf", "rerr", "segv"):
    check(all("instructions" not in r and "libc_bytes" not in r for r in recs[n]), "%s: has counts" % n)
if bad:
    print("FAIL:\n  " + "\n  ".join(bad), file=sys.stderr)
    sys.exit(1)
print("perf selftest: ok (%d fixtures, counts equal or within the stated bound across two cold builds)" % len(fixtures))
PY

# ==== T090: judging against complexity classes, and perf-killed mutants ============================
# One package of five modules, each with a c_perf at its honest class (flat O(1), bsearch O(log n), lin O(n), nlogn
# O(n log n), quad O(n^2)), judged by perf_judge against every class: the matrix of who is inside which class is
# exact. `flat` is a hash set whose lookups are O(1); its `c_mutants` must turn the mutants that make the
# lookup O(n) (the hash replaced by `return 0`) into killed-perf, while the same mutants survive when the report is judged
# without the perf evidence.
judge="selftest/scratch_perf_judge"
trap 'rm -rf "$scratch" "$judge" "$out"' EXIT
mkdir -p "$judge"
cat > "$judge/gen.inc" <<'C'
static size_t fill(uint64_t seed, size_t n, char *out, size_t cap) {
    uint64_t x = seed * 6364136223846793005ULL + 1442695040888963407ULL;
    size_t i;
    if (n > cap) { return 0; }
    for (i = 0; i < n; i++) {
        x = x * 6364136223846793005ULL + 1442695040888963407ULL;
        out[i] = (char)(x >> 56);
    }
    return n;
}
C
cat > "$judge/flat.h" <<'C'
#ifndef FLAT_H
#define FLAT_H
#include <stddef.h>
#include <stdint.h>

/* A set of nonzero 32-bit keys: open addressing over a caller-provided power-of-two slot array. */
struct flat {
    uint32_t *slots;
    size_t mask;
};

void flat_init(struct flat *m, uint32_t *slots, size_t cap);
int flat_insert(struct flat *m, uint32_t key);
int flat_contains(const struct flat *m, uint32_t key);
#endif
C
cat > "$judge/flat.c" <<'C'
#include "flat.h"

static size_t flat_slot(uint32_t key, size_t mask)
{
    return (size_t)((key * 2654435761u) >> 11) & mask;
}

void flat_init(struct flat *m, uint32_t *slots, size_t cap)
{
    size_t i;
    m->slots = slots;
    m->mask = cap - 1;
    for (i = 0; i < cap; i++) {
        slots[i] = 0;
    }
}

int flat_insert(struct flat *m, uint32_t key)
{
    size_t i = flat_slot(key, m->mask);
    size_t probes;
    for (probes = 0; probes <= m->mask; probes++) {
        if (m->slots[i] == key) {
            return 0;
        }
        if (m->slots[i] == 0) {
            m->slots[i] = key;
            return 1;
        }
        i = (i + 1) & m->mask;
    }
    return -1;
}

int flat_contains(const struct flat *m, uint32_t key)
{
    size_t i = flat_slot(key, m->mask);
    size_t probes;
    for (probes = 0; probes <= m->mask; probes++) {
        if (m->slots[i] == key) {
            return 1;
        }
        if (m->slots[i] == 0) {
            return 0;
        }
        i = (i + 1) & m->mask;
    }
    return 0;
}
