#!/usr/bin/env python3
"""Convert recorded relay-board conformance runs into `fr` records for the wire invariants (T2G3, P330 sections 1.5, 2.5).

The positive control of the independent frame model: the recording of the REAL board (and of the club-apps simulator) must
PASS I3 to I6b, so the model is tied to the device and not only to our own simulator.

Input: the JSON of club-apps `tools/conformance` (`exchanges`: `t_ms` the request time, `dt_ms` the delay of the reply,
`request` and `response` as hex). Each exchange becomes two `fr` records: the request at `t_ms` (direction 0) and the response
at `t_ms + dt_ms` (direction 1). `host` and `port` are never copied; the output is refused if it matches an IPv4 address.

The recorded script paces its three flights 10 ms apart (flash relay 13, then relay 1, then both), where the kiosk waits
300 ms and takes a fresh read before each pulse (hardware-safety Rules for code 3). So the control is checked per flight:
the recording is cut into segments, each a single flight, and the all-off read that verifies one flight is repeated as the
first record of the next (it is both the verify read and the only read before the next flash). The uncut recording is kept as
`whole`; the tests pin that it FAILS I5 (gap and fresh read), so the control cannot pass by accident.

Usage: fixture_to_fr.py --real REAL.json --sim SIM.json --out-dir DIR     writes DIR/fixtures_data.h and DIR/fixtures_data.c
       fixture_to_fr.py --check ... (same arguments)                      fails if the files in DIR differ from the output
Python 3 standard library only. Deterministic.
"""

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

IPV4 = re.compile(r"(?<![0-9])[0-9]{1,3}(\.[0-9]{1,3}){3}(?![0-9])")
READ_ALL = bytes.fromhex("010100000" + "01e")  # slave 1, FC01, address 0, 30 coils (CRC follows)
FLASH_PREFIX = bytes([0x01, 0x05, 0x02])
MAX_FRAME = 16


class ConvertError(Exception):
    pass


def load(path):
    """The exchanges of a recording as (t_ms, dt_ms, request bytes, response bytes), checked."""
    try:
        data = json.loads(Path(path).read_text())
    except (OSError, ValueError) as err:
        raise ConvertError("%s: cannot read: %s" % (path, err))
    exchanges = data.get("exchanges") if isinstance(data, dict) else None
    if not isinstance(exchanges, list) or not exchanges:
        raise ConvertError("%s: no exchanges" % path)
    out = []
    for i, e in enumerate(exchanges):
        try:
            item = (int(e["t_ms"]), int(e["dt_ms"]), bytes.fromhex(e["request"]), bytes.fromhex(e["response"]))
        except (KeyError, ValueError, TypeError) as err:
            raise ConvertError("%s: exchange %d is malformed: %s" % (path, i, err))
        if item[0] < 0 or item[1] < 0 or not 0 < len(item[2]) <= MAX_FRAME or not 0 < len(item[3]) <= MAX_FRAME:
            raise ConvertError("%s: exchange %d is out of range" % (path, i))
        out.append(item)
    return out


def is_all_off_read(ex):
    _, _, req, resp = ex
    return req[:6] == READ_ALL and len(resp) == 9 and resp[:3] == bytes([1, 1, 4]) and resp[3:7] == bytes(4)


def is_flash(ex):
    return ex[2][:3] == FLASH_PREFIX


def segments(exchanges):
    """Cut the recording into one segment per flight; a verify read that is followed by a flash ends one and starts the next."""
    out, cur, has_flash = [], [], False
    for i, ex in enumerate(exchanges):
        nxt = exchanges[i + 1] if i + 1 < len(exchanges) else None
        cur.append(ex)
        if is_flash(ex):
            has_flash = True
        elif has_flash and nxt is not None and is_all_off_read(ex) and is_flash(nxt):
            out.append(cur)
            cur, has_flash = [ex], False
    out.append(cur)
    return out


def records(exchanges):
    """Two `fr` records per exchange, in order; times must not go backwards (a recording that does is refused, not repaired)."""
    out, last = [], 0
    for t, dt, req, resp in exchanges:
        for when, direction, frame in ((t, 0, req), (t + dt, 1, resp)):
            if when < last:
                raise ConvertError("time goes backwards at %d ms (after %d ms)" % (when, last))
            last = when
            out.append((when, direction, frame))
    return out


def c_trace(name, recs):
    lines = ["static const fx_rec_t %s[] = {" % name]
    for t, direction, frame in recs:
        lines.append("    {%dULL, %d, %d, {%s}}," % (t, direction, len(frame), ", ".join("0x%02x" % b for b in frame)))
    lines.append("};")
    return lines


HEADER = """/* GENERATED by tools/sim/fixture_to_fr.py from selftest/sim/data (sha256 below). Do not edit: gate/tests/test_sim_wire_fixtures.py
 * regenerates it and fails on any difference. Records of kind "fr": `dir` 0 is a request, 1 a response. */
#ifndef SIM_INV_TESTS_FIXTURES_DATA_H
#define SIM_INV_TESTS_FIXTURES_DATA_H

#include <stddef.h>
#include <stdint.h>

typedef struct {
    uint64_t t_ms;
    uint8_t dir;
    uint8_t len;
    uint8_t bytes[%d];
} fx_rec_t;

typedef struct {
    const fx_rec_t *recs;
    size_t n;
} fx_trace_t;

"""


def build(sources):
    """sources: [(prefix, path)] -> (header text, c text)."""
    head = [HEADER % MAX_FRAME]
    body = ['/* GENERATED by tools/sim/fixture_to_fr.py. Do not edit. */', '#include "sim/inv/tests/fixtures_data.h"', ""]
    for prefix, path in sources:
        exchanges = load(path)
        digest = hashlib.sha256(Path(path).read_bytes()).hexdigest()
        segs = segments(exchanges)
        head.append("/* %s: %s (sha256 %s), %d exchanges, %d flights */" % (prefix, Path(path).name, digest, len(exchanges), len(segs)))
        head.append("#define FX_%s_NSEGS %d" % (prefix.upper(), len(segs)))
        head.append("extern const fx_trace_t FX_%s_SEGS[FX_%s_NSEGS];" % (prefix.upper(), prefix.upper()))
        head.append("extern const fx_trace_t FX_%s_WHOLE;" % prefix.upper())
        head.append("")
        names = []
        for k, seg in enumerate(segs):
            name = "fx_%s_seg%d" % (prefix, k)
            names.append(name)
            body += c_trace(name, records(seg)) + [""]
        body += c_trace("fx_%s_whole" % prefix, records(exchanges)) + [""]
        body.append("const fx_trace_t FX_%s_SEGS[FX_%s_NSEGS] = {" % (prefix.upper(), prefix.upper()))
        body += ["    {%s, sizeof %s / sizeof %s[0]}," % (n, n, n) for n in names]
        body.append("};")
        body.append("const fx_trace_t FX_%s_WHOLE = {fx_%s_whole, sizeof fx_%s_whole / sizeof fx_%s_whole[0]};" % ((prefix.upper(),) + (prefix,) * 3))
        body.append("")
    head.append("#endif")
    h, c = "\n".join(head) + "\n", "\n".join(body)
    for text in (h, c):
        if IPV4.search(text):
            raise ConvertError("the output contains an IPv4 literal; refusing to write it")
    return h, c


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--real", required=True)
    ap.add_argument("--sim", required=True)
    ap.add_argument("--out-dir", required=True)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    try:
        h, c = build([("real", args.real), ("sim", args.sim)])
    except ConvertError as err:
        print("fixture_to_fr: %s" % err, file=sys.stderr)
        return 2
    out = Path(args.out_dir)
    files = {"fixtures_data.h": h, "fixtures_data.c": c + "\n" if not c.endswith("\n") else c}
    if args.check:
        bad = [n for n, text in files.items() if not (out / n).is_file() or (out / n).read_text() != text]
        for n in bad:
            print("fixture_to_fr: %s differs from the converter output" % n, file=sys.stderr)
        return 1 if bad else 0
    for n, text in files.items():
        (out / n).write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
