"""Tests for `bin2c` and the `c_embed` build-file rules (T112): round trip, header text, every refusal, `rigor buckfiles`."""

import re
import subprocess
import sys

from rigor_lib import bin2c
from tests.helpers import GATE_DIR, TempDirTestCase, read_json, run_rigor

TOOL = str(GATE_DIR / "rigor_lib" / "bin2c.py")
HEADER = "pkg/blob.h"


def parse_bytes(source):
    """The byte values of the generated array text (what a C compiler would see)."""
    body = source[source.index("= {") + 3:source.index("};")]
    return bytes(int(h, 16) for h in re.findall(r"0x([0-9a-f]{2})", body))


class RenderCase(TempDirTestCase):
    def build(self, data, symbol="blob", limit=1024):
        src = self.tmp / "in.bin"
        src.write_bytes(data)
        return bin2c.build(symbol, limit, HEADER, str(src))

    def test_bytes_round_trip_including_zero_and_ff(self):
        data = bytes([0, 255, 0, 255, 1, 2, 3]) + bytes(range(256))
        _, source = self.build(data)
        self.assertEqual(parse_bytes(source), data)

    def test_sizes_that_are_no_multiple_of_a_line_width(self):
        for size in (1, 2, 15, 16, 17, 31, 33, 255, 257):
            with self.subTest(size=size):
                data = bytes((n * 7 + 3) % 256 for n in range(size))
                _, source = self.build(data)
                self.assertEqual(parse_bytes(source), data)
                self.assertIn("const size_t blob_len = %d;" % size, source)
                self.assertIn("const unsigned char blob[%d] = {" % size, source)

    def test_no_terminator_and_no_stray_entries(self):
        _, source = self.build(b"\x41")
        self.assertEqual(parse_bytes(source), b"\x41")
        self.assertEqual(source.count("0x"), 1)

    def test_lines_have_sixteen_bytes(self):
        _, source = self.build(bytes(40))
        rows = [line for line in source.splitlines() if line.startswith("    0x")]
        self.assertEqual([line.count("0x") for line in rows], [16, 16, 8])

    def test_the_header_text(self):
        header, _ = self.build(b"x", symbol="font_ttf")
        self.assertEqual(header, "\n".join([
            "/* Generated by bin2c.py from a checked-in binary file. Do not edit. */",
            "#ifndef C_EMBED_FONT_TTF_H", "#define C_EMBED_FONT_TTF_H", "", "#include <stddef.h>", "",
            "extern const unsigned char font_ttf[];", "extern const size_t font_ttf_len;", "", "#endif", ""]))

    def test_the_source_includes_the_header_and_is_const(self):
        _, source = self.build(b"x")
        self.assertIn('#include "pkg/blob.h"', source)
        self.assertIn("\nconst unsigned char blob[1] = {", source)
        self.assertNotIn("static", source)

    def test_the_output_is_deterministic_ascii(self):
        first, second = self.build(b"\x00\xff"), self.build(b"\x00\xff")
        self.assertEqual(first, second)
        for text in first:
            text.encode("ascii")

    def test_nul_adds_one_zero_byte_inside_the_array_and_the_length_stays(self):
        data = bytes([0, 255, 7])
        _, plain = self.build(data)
        _, with_nul = bin2c.build("blob", 1024, HEADER, str(self.tmp / "in.bin"), nul=True)
        self.assertEqual(parse_bytes(plain), data)
        self.assertEqual(parse_bytes(with_nul), data + b"\x00")
        self.assertIn("const unsigned char blob[4] = {", with_nul)
        self.assertIn("const size_t blob_len = 3;", with_nul)
        self.assertIn("const unsigned char blob[3] = {", plain)

    def test_nul_does_not_change_the_header_or_the_limit(self):
        header, _ = self.build(b"abc")
        header_nul, _ = bin2c.build("blob", 3, HEADER, str(self.tmp / "in.bin"), nul=True)
        self.assertEqual(header, header_nul)

    def test_nul_with_a_file_over_the_limit_is_still_refused(self):
        (self.tmp / "big.bin").write_bytes(bytes(11))
        with self.assertRaises(bin2c.EmbedError):
            bin2c.build("blob", 10, HEADER, str(self.tmp / "big.bin"), nul=True)

    def test_a_file_exactly_at_the_limit_is_fine(self):
        _, source = self.build(bytes(10), limit=10)
        self.assertEqual(parse_bytes(source), bytes(10))


class RefusalCase(TempDirTestCase):
    def red(self, needle, symbol="blob", limit=100, data=b"abc", header=HEADER, name="in.bin"):
        src = self.tmp / name
        if data is not None:
            src.write_bytes(data)
        with self.assertRaises(bin2c.EmbedError) as caught:
            bin2c.build(symbol, limit, header, str(src))
        self.assertIn(needle, str(caught.exception))

    def test_symbols_that_are_not_c_identifiers(self):
        for symbol in ("", "1a", "_a", "a-b", "a b", "a.b", "a;b", "a\nb", "é", "a" * 64):
            with self.subTest(symbol=symbol):
                self.red("symbol", symbol=symbol)

    def test_c_keywords_are_not_symbols(self):
        for symbol in ("int", "const", "static", "while", "NULL", "bool"):
            with self.subTest(symbol=symbol):
                self.red("keyword", symbol=symbol)

    def test_good_symbols(self):
        for symbol in ("a", "A1_b", "a" * 63, "font_len"):
            with self.subTest(symbol=symbol):
                self.assertEqual(bin2c.check_symbol(symbol), symbol)

    def test_an_empty_file(self):
        self.red("empty", data=b"")

    def test_a_file_over_max_bytes(self):
        self.red("over max_bytes 10", limit=10, data=bytes(11))

    def test_a_missing_file(self):
        self.red("cannot read", data=None, name="missing.bin")

    def test_a_directory_is_not_a_file(self):
        (self.tmp / "dir").mkdir()
        self.red("not a regular file", data=None, name="dir")

    def test_max_bytes_bounds(self):
        for limit in (0, -1, 16 * 1024 * 1024 + 1, True, "5"):
            with self.subTest(limit=limit):
                self.red("max_bytes", limit=limit)
        self.assertEqual(bin2c.check_limit(16 * 1024 * 1024), 16 * 1024 * 1024)
        self.assertEqual(bin2c.check_limit(1), 1)

    def test_bad_include_paths(self):
        for header in ("", "a b.h", "../x.h", "a/../x.h", "a;b.h"):
            with self.subTest(header=header):
                self.red("include path", header=header)


class CommandLineCase(TempDirTestCase):
    def run_tool(self, data, *extra, symbol="blob", limit="1000"):
        src = self.tmp / "in.bin"
        src.write_bytes(data)
        command = [sys.executable, "-I", "-B", TOOL, "--symbol", symbol, "--max-bytes", limit, "--header", HEADER,
                   "--src", str(src), "--out-h", str(self.tmp / "o.h"), "--out-c", str(self.tmp / "o.c"), *extra]
        return subprocess.run(command, capture_output=True, text=True, timeout=60)

    def test_the_nul_flag_appends_one_zero_byte(self):
        done = self.run_tool(b"ab", "--nul")
        self.assertEqual(done.returncode, 0, done.stderr)
        source = (self.tmp / "o.c").read_text(encoding="ascii")
        self.assertEqual(parse_bytes(source), b"ab\x00")
        self.assertIn("const size_t blob_len = 2;", source)

    def test_writes_both_files(self):
        done = self.run_tool(b"\x00\x01")
        self.assertEqual(done.returncode, 0, done.stderr)
        self.assertEqual(parse_bytes((self.tmp / "o.c").read_text()), b"\x00\x01")
        self.assertIn("extern const size_t blob_len;", (self.tmp / "o.h").read_text())

    def test_a_refusal_exits_one_with_one_line_and_no_output(self):
        done = self.run_tool(b"")
        self.assertEqual(done.returncode, 1)
        self.assertEqual(done.stderr.count("\n"), 1)
        self.assertTrue(done.stderr.startswith("bin2c: error: "))
        self.assertFalse((self.tmp / "o.c").exists() or (self.tmp / "o.h").exists())

    def test_a_bad_symbol_exits_one(self):
        done = self.run_tool(b"x", symbol="9x")
        self.assertEqual(done.returncode, 1)
        self.assertIn("not a C identifier", done.stderr)


LOAD = 'load("@gate//rules:c.bzl", "c_embed", "c_library")\n'
OK = 'c_embed(name = "font", src = "font.ttf", symbol = "font_ttf", max_bytes = 500000, visibility = ["PUBLIC"])\n'


class BuckFilesCase(TempDirTestCase):
    def check(self, source, code):
        root = self.sub("product")
        (root / "BUCK").write_text(source, encoding="utf-8")
        self.assertExit(run_rigor(["buckfiles", "--root", root, "--out", self.tmp / "out.json"]), code)
        return sorted((f["rule"], f.get("why")) for f in read_json(self.tmp / "out.json")["findings"])

    def bad(self, source, why="value"):
        self.assertEqual(self.check(source, 1), [("bad-argument", why)])

    def test_the_literal_call_is_accepted(self):
        self.assertEqual(self.check(LOAD + OK, 0), [])
        self.assertEqual(self.check(LOAD + 'c_embed(name = "f", src = "f.bin", symbol = "f")\n', 0), [])

    def test_a_c_library_may_depend_on_it(self):
        self.assertEqual(self.check(LOAD + OK + 'c_library(name = "ui", srcs = ["ui.c"], deps = [":font"])\n', 0), [])

    def test_non_literal_values_are_refused(self):
        for key, value in (("src", '"a" + ".bin"'), ("src", "NAME"), ("src", 'glob(["*.bin"])'), ("src", '["a.bin"]'),
                           ("symbol", "SYM"), ("symbol", '["x"]'), ("symbol", '"a" + "b"'),
                           ("max_bytes", '"5"'), ("max_bytes", "True"), ("max_bytes", "2 * 5"), ("max_bytes", "-1"),
                           ("max_bytes", "5.0"), ("max_bytes", "LIMIT"), ("max_bytes", "[5]"),
                           ("visibility", "1")):
            with self.subTest(key=key, value=value):
                self.setUp()
                self.bad(LOAD + 'c_embed(name = "f", src = "f.bin", symbol = "f", %s = %s)\n' % (key, value))

    def test_nul_is_a_bool_literal(self):
        self.assertEqual(self.check(LOAD + 'c_embed(name = "f", src = "f.bin", symbol = "f", nul = True)\n', 0), [])
        self.assertEqual(self.check(LOAD + 'c_embed(name = "f", src = "f.bin", symbol = "f", nul = False)\n', 0), [])
        for value in ("1", '"True"', "NUL", "not False", "[True]"):
            with self.subTest(value=value):
                self.setUp()
                self.bad(LOAD + 'c_embed(name = "f", src = "f.bin", symbol = "f", nul = %s)\n' % value)

    def test_other_keywords_are_refused(self):
        for extra in ('srcs = ["a.c"]', 'headers = ["a.h"]', 'deps = [":x"]', 'compiler_flags = ["-w"]',
                      'system_libs = ["pthread"]', "**{}", 'pots = ["a.pot"]'):
            with self.subTest(extra=extra):
                self.setUp()
                self.bad(LOAD + 'c_embed(name = "f", src = "f.bin", symbol = "f", %s)\n' % extra, "keyword")

    def test_positional_is_refused(self):
        self.bad(LOAD + 'c_embed("f")\n', "positional")

    def test_its_keywords_are_not_the_others(self):
        for key, value in (("src", '"x"'), ("symbol", '"x"'), ("max_bytes", "5"), ("nul", "True")):
            with self.subTest(key=key):
                self.setUp()
                self.bad(LOAD + 'c_library(name = "a", %s = %s)\n' % (key, value), "keyword")

    def test_native_calls_are_still_refused(self):
        self.assertEqual(self.check(LOAD + 'native.cxx_library(name = "a")\n', 1), [("bad-call", None)])
