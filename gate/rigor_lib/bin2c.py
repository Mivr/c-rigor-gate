"""`bin2c`: one checked-in binary file -> a const C byte array and its length (T112, `c_embed`, docs/grade.md).

Runs inside a Buck2 action (`rules/embed.bzl`) and in the unit tests; Python 3.8+ stdlib only, no import of the
rest of the gate (a Buck action runs it with `python3 -I -B`).

    python3 -I -B bin2c.py --symbol S --max-bytes N --header pkg/name.h --src FILE --out-h FILE --out-c FILE

The header declares `extern const unsigned char S[];` and `extern const size_t S_len;`. The source defines both as
const objects (read-only data): `S` holds exactly the bytes of the file, no terminator, and `S_len` is the file size.
The output is a pure function of the inputs. Every refusal is a build error (exit 1, one line on stderr, no output
file): a symbol that is not a C identifier, a file that is empty, over `--max-bytes`, or not a regular file, and a
`--max-bytes` outside 1..16 MiB.
"""

import argparse
import os
import re
import stat
import sys

MAX_LIMIT = 16 * 1024 * 1024
PER_LINE = 16
MAX_SYMBOL = 63
SYMBOL = re.compile(r"[A-Za-z][A-Za-z0-9_]*\Z")
HEADER_PATH = re.compile(r"[A-Za-z0-9_./+-]+\Z")
C_KEYWORDS = frozenset((
    "auto break case char const continue default do double else enum extern float for goto if inline int long "
    "register restrict return short signed sizeof static struct switch typedef union unsigned void volatile while "
    "bool true false NULL").split()
    + ["_Alignas", "_Alignof", "_Atomic", "_Bool", "_Complex", "_Generic", "_Imaginary", "_Noreturn",
       "_Static_assert", "_Thread_local"])


class EmbedError(Exception):
    """A build error; the text says what is wrong and with which value."""


def check_symbol(symbol):
    if not isinstance(symbol, str) or not SYMBOL.match(symbol):
        raise EmbedError("symbol %r is not a C identifier ([A-Za-z][A-Za-z0-9_]*)" % (symbol,))
    if len(symbol) > MAX_SYMBOL:
        raise EmbedError("symbol %r is longer than %d characters" % (symbol, MAX_SYMBOL))
    if symbol in C_KEYWORDS:
        raise EmbedError("symbol %r is a C keyword or a standard macro name" % symbol)
    return symbol


def check_limit(limit):
    if type(limit) is not int or limit < 1 or limit > MAX_LIMIT:
        raise EmbedError("max_bytes %r must be an integer from 1 to %d (16 MiB)" % (limit, MAX_LIMIT))
    return limit


def check_header_path(path):
    if not HEADER_PATH.match(path) or ".." in path.split("/"):
        raise EmbedError("%r is not a plain include path" % path)
    return path


def read_asset(path, limit):
    """The bytes of the regular file `path`, 1 to `limit` of them."""
    try:
        info = os.stat(path)
    except OSError as error:
        raise EmbedError("%s: cannot read: %s" % (path, error.strerror))
    if not stat.S_ISREG(info.st_mode):
        raise EmbedError("%s: not a regular file" % path)
    if info.st_size == 0:
        raise EmbedError("%s: the file is empty" % path)
    if info.st_size > limit:
        raise EmbedError("%s: %d bytes is over max_bytes %d" % (path, info.st_size, limit))
    with open(path, "rb") as handle:
        data = handle.read(limit + 1)
    if not data or len(data) > limit:
        raise EmbedError("%s: size changed while reading" % path)
    return data


def render_header(symbol):
    guard = "C_EMBED_%s_H" % symbol.upper()
    return "\n".join([
        "/* Generated by bin2c.py from a checked-in binary file. Do not edit. */",
        "#ifndef %s" % guard, "#define %s" % guard, "", "#include <stddef.h>", "",
        "extern const unsigned char %s[];" % symbol,
        "extern const size_t %s_len;" % symbol, "", "#endif", ""])


def render_source(symbol, header, data):
    lines = ["/* Generated by bin2c.py from a checked-in binary file. Do not edit. */",
             '#include "%s"' % header, "", "#include <stddef.h>", "",
             "const unsigned char %s[%d] = {" % (symbol, len(data))]
    for start in range(0, len(data), PER_LINE):
        lines.append("    " + ", ".join("0x%02x" % b for b in data[start:start + PER_LINE]) + ",")
    lines += ["};", "", "const size_t %s_len = %d;" % (symbol, len(data)), ""]
    return "\n".join(lines)


def write(path, text):
    with open(path, "wb") as handle:
        handle.write(text.encode("ascii"))


def build(symbol, limit, header, src):
    """-> (header text, source text); raises EmbedError."""
    check_symbol(symbol)
    check_limit(limit)
    check_header_path(header)
    data = read_asset(src, limit)
    return render_header(symbol), render_source(symbol, header, data)


def parser():
    p = argparse.ArgumentParser(prog="bin2c", allow_abbrev=False)
    p.add_argument("--symbol", required=True)
    p.add_argument("--max-bytes", required=True, type=int)
    p.add_argument("--header", required=True, help="include path of the generated header")
    p.add_argument("--src", required=True)
    p.add_argument("--out-h", required=True)
    p.add_argument("--out-c", required=True)
    return p


def main(argv):
    args = parser().parse_args(argv)
    try:
        header, source = build(args.symbol, args.max_bytes, args.header, args.src)
    except EmbedError as error:
        print("bin2c: error: %s" % error, file=sys.stderr)
        return 1
    write(args.out_h, header)
    write(args.out_c, source)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
