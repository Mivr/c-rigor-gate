"""The decoupling baseline (`products/<product>/decoupling-baseline.toml`): the violations a product is still
allowed, and the ratchet over it.

Gate-owned, next to `product.toml`, written by `gate/tools/decoupling.py baseline`. One key per rule, each a sorted
list of violation keys without duplicates (`"<target> -> <dep>"`, `"<test> -> <module>"`, `"<target>"`, ...):

    unused-dep = [
        "//apps/shop/parts/cart:cart -> //lib/base/text:text",
    ]

A rule that is absent tolerates nothing. Any defect is exit 2 (InternalError): an unknown rule, an entry that is
not a key, a list that is not sorted. The ratchet (`judge`):
  * a violation of the tree that the list does not name is an error finding named after its rule;
  * an entry that is no longer a violation of the tree is the error `stale-baseline`: the change that removes a
    violation lands with a gate that no longer lists it, so the list only shrinks and a fixed problem cannot return.
"""

import re
import tomllib

from rigor_lib import jsonio
from rigor_lib.decoupling_rules import RULES
from rigor_lib.errors import InternalError
from rigor_lib.findings import finding

FILE_NAME = "decoupling-baseline.toml"
STALE = "stale-baseline"
_NAME = r"[A-Za-z0-9_.$@/:+-]+"     # a label or a symbol: nothing a TOML string would need to escape
KEY = re.compile(r"%s(?: (?:->|:) %s)?" % (_NAME, _NAME))
HEADER = "# The violations of the decoupling rules this product is still allowed (docs/decoupling.md).\n" \
         "# Generated by gate/tools/decoupling.py baseline; entries are only ever removed.\n"


def _fail(why):
    raise InternalError("decoupling baseline: %s" % why)


def parse(text):
    """-> {rule: frozenset of keys} for every rule (an absent rule has none)."""
    try:
        document = tomllib.loads(text)
    except ValueError as exc:
        raise InternalError("decoupling baseline is not valid TOML: %s" % exc) from exc
    unknown = sorted(set(document) - set(RULES))
    if unknown:
        _fail("unknown rule %s" % ", ".join(unknown))
    baseline = {}
    for rule in RULES:
        entries = document.get(rule, [])
        if not isinstance(entries, list) or not all(isinstance(e, str) and KEY.fullmatch(e) for e in entries):
            _fail("%s must be a list of violation keys" % rule)
        if entries != sorted(set(entries)):
            _fail("%s must be sorted and without duplicates" % rule)
        baseline[rule] = frozenset(entries)
    return baseline


def load(path):
    try:
        return parse(jsonio.read_bytes(path).decode("utf-8"))
    except UnicodeDecodeError as exc:
        raise InternalError("%s: not UTF-8" % path) from exc


def render(violations):
    """The baseline file that tolerates exactly `violations` ({rule: keys}); `parse(render(v))` gives them back."""
    out = [HEADER]
    for rule in RULES:
        keys = sorted(violations.get(rule, ()))
        for key in keys:
            if not KEY.fullmatch(key):
                _fail("%s: %r is not a violation key" % (rule, key))
        out.append("%s = [%s]\n" % (rule, "".join('\n    "%s",' % key for key in keys) + ("\n" if keys else "")))
    return "\n".join(out)


def judge(violations, baseline):
    """-> (findings, {rule: {"violations", "new", "stale"}}). `violations`: {rule: {key: fields}}."""
    found, counts = [], {}
    for rule in RULES:
        present, tolerated = violations.get(rule, {}), baseline.get(rule, frozenset())
        new = sorted(set(present) - tolerated)
        stale = sorted(tolerated - set(present))
        found.extend(finding(rule, entry=key, **present[key]) for key in new)
        found.extend(finding(STALE, list=rule, entry=key) for key in stale)
        counts[rule] = {"violations": len(present), "new": len(new), "stale": len(stale)}
    return found, counts
